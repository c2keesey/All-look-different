import json, sys, os, re, shutil, html, urllib.request
data = json.load(open(sys.argv[1])); crops = sys.argv[2]; repo = sys.argv[3]
PICK = {
 "british": [3,11,13,15,22,26,29,30,31,32,34,36,42,46,47,50,53,55,58,59,68,71,82,86,87,93,95],
 "german":  [0,9,12,15,16,18,20,22,23,26,28,29,33,35,36,38,44,50,51,52,53,72,82,91,94,104,107,118],
 "french":  [0,5,7,14,16,20,21,25,32,34,44,45,48,49,52,56,60,66,67,70,73,74,76,77,83,84,86,87],
}
def clean(s):
    s = re.sub(r"<[^>]+>", "", s); s = html.unescape(s); s = re.sub(r"^User:", "", re.sub(r"\s+", " ", s).strip()); return s[:120] or "a Wikimedia Commons contributor"
outdir = os.path.join(repo, "images", "faces"); os.makedirs(outdir, exist_ok=True)
faces = []
for nat, idxs in PICK.items():
    for i in idxs:
        r = data[nat][i]
        if re.fullmatch(r"Q\d+", r["name"]):  # no English label: take the multilingual one
            req = urllib.request.Request(f"https://www.wikidata.org/w/api.php?action=wbgetentities&ids={r['qid']}&props=labels&format=json",
                                         headers={"User-Agent": "AllLookDifferentQuizBuilder/1.0"})
            labels = json.load(urllib.request.urlopen(req))["entities"][r["qid"]]["labels"]
            r["name"] = (labels.get("mul") or next(iter(labels.values())))["value"]
        shutil.copy(os.path.join(crops, r["qid"] + ".jpg"), os.path.join(outdir, r["qid"] + ".jpg"))
        faces.append({"id": r["qid"], "nationality": nat, "name": r["name"], "born": int(r["born"]),
                      "image": f"images/faces/{r['qid']}.jpg", "author": clean(r["artist"]), "license": r["license"],
                      "licenseUrl": r["license_url"], "source": r["page"], "wikidata": f"https://www.wikidata.org/wiki/{r['qid']}"})
with open(os.path.join(repo, "faces.js"), "w") as f:
    f.write("// Generated by scripts/build_faces.py from Wikidata + Wikimedia Commons. Do not edit by hand.\n")
    f.write("// Every photo is cropped from a freely licensed Commons original; see author/license/source.\n")
    f.write("const FACES = " + json.dumps(faces, indent=1, ensure_ascii=False) + ";\n")
json.dump(faces, open(os.path.join(repo, "faces.json"), "w"), ensure_ascii=False, indent=1)
print(len(faces), {n: len(v) for n, v in PICK.items()})
